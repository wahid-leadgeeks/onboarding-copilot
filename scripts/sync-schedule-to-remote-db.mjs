async function syncToRemoteNova() {
  console.log('Connecting to remote NOVA PostgreSQL database...');
  const connStr = process.argv[2] || process.env.DATABASE_URL;
  if (!connStr) {
    console.error('DATABASE_URL is required. Provide it as an argument or set DATABASE_URL environment variable.');
    process.exit(1);
  }
  const sql = postgres(connStr);

  console.log('1. Ensuring activities schema has materials_link and nullable activity_count...');
  await sql`ALTER TABLE activities ADD COLUMN IF NOT EXISTS materials_link text DEFAULT '';`;
  await sql`ALTER TABLE activities ALTER COLUMN activity_count DROP NOT NULL;`;

  console.log('2. Cleaning up legacy or deleted activity records not in official 53 items...');
  const validIds = SCHEDULE_DATA.map(a => a.id);
  const deleted = await sql`DELETE FROM activities WHERE id NOT IN ${sql(validIds)}`;
  console.log(`Deleted ${deleted.count} stale activities.`);

  console.log('3. Upserting all 53 official schedule activities...');
  for (const item of SCHEDULE_DATA) {
    await sql`
      INSERT INTO activities (
        id,
        row_number,
        week,
        day,
        date,
        activity_count,
        pic,
        topic,
        main_media,
        duration_minutes,
        start_time,
        end_time,
        progress,
        materials_link,
        notes,
        updated_at
      ) VALUES (
        ${item.id},
        ${item.rowNumber},
        ${item.week},
        ${item.day},
        ${item.date},
        ${item.activityCount},
        ${item.pic},
        ${item.topic},
        ${item.mainMedia},
        ${item.durationMinutes},
        ${item.startTime || null},
        ${item.endTime || null},
        ${item.progress},
        ${item.materialsLink || ''},
        ${item.notes || ''},
        NOW()
      )
      ON CONFLICT (id) DO UPDATE SET
        row_number = EXCLUDED.row_number,
        week = EXCLUDED.week,
        day = EXCLUDED.day,
        date = EXCLUDED.date,
        activity_count = EXCLUDED.activity_count,
        pic = EXCLUDED.pic,
        topic = EXCLUDED.topic,
        main_media = EXCLUDED.main_media,
        duration_minutes = EXCLUDED.duration_minutes,
        start_time = EXCLUDED.start_time,
        end_time = EXCLUDED.end_time,
        progress = EXCLUDED.progress,
        materials_link = EXCLUDED.materials_link,
        notes = EXCLUDED.notes,
        updated_at = NOW()
    `;
  }

  console.log('4. Verifying synced activities in database...');
  const countRes = await sql`SELECT count(*) FROM activities`;
  console.log(`Total activities in remote DB: ${countRes[0].count}`);

  const sample = await sql`
    SELECT id, row_number, activity_count, topic, duration_minutes, start_time, end_time, progress, notes, materials_link
    FROM activities
    WHERE row_number IN (3, 20, 27, 36, 44, 53, 56, 58)
    ORDER BY row_number ASC
  `;
  console.log('Verification sample:');
  for (const r of sample) {
    console.log(`Row ${r.row_number} | #${r.activity_count || '-'} | prog=${r.progress} | dur=${r.duration_minutes}m (${r.start_time}-${r.end_time}) | mat=${r.materials_link ? 'YES' : 'NO'} | note=${r.notes}`);
  }

  await sql.end();
  console.log('Sync to remote NOVA database completed successfully!');
}

if (process.argv[1] && process.argv[1].endsWith('sync-schedule-to-remote-db.mjs')) {
  syncToRemoteNova().catch((err) => {
    console.error('Migration failed:', err);
    process.exit(1);
  });
}
